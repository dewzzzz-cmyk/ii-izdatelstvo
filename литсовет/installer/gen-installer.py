# В CP866 нет длинного тире, многоточия и типографских кавычек-лапок. Молча
# упасть на кодировании нельзя, но и молча выбросить символ — тоже: получится
# текст с дырками. Заменяем на то, что в 866 есть, и после этого ПРОВЕРЯЕМ,
# что обратное декодирование даёт ровно то, что мы собирались записать.
ЗАМЕНЫ = {
    '—': '-',      # — длинное тире
    '–': '-',      # – среднее тире
    '…': '...',    # … многоточие
    '“': '"', '”': '"', '„': '"',
    '«': '"', '»': '"',   # в cp866 их нет — проверено кодированием
    '‘': "'", '’': "'",
    ' ': ' ',      # неразрывный пробел
}

def под866(t):
    for a, b in ЗАМЕНЫ.items():
        t = t.replace(a, b)
    return t

# `pause` под перенаправлённым (не консольным) stdin читает не «одну строку»,
# как set /p, а по своей внутренней логике — на практике это подтверждено
# минимальным повторением: три set /p с обычным pause между первым и вторым
# дали смещение (второй set /p получил пустую строку вместо своего ответа,
# третий — чужой). Тот же ввод с pause, заменённым на set /p с тем же текстом
# подсказки, дал точное совпадение построчно. Для интерактивного пользователя
# (двойной клик) разницы нет — Enter работает одинаково в обоих случаях, а
# скрипт от этого становится предсказуем при ЛЮБОМ способе передать ввод, не
# только при обычной консоли. Поэтому bare `pause` заменяется механически.
def без_pause(t):
    def замена(m):
        отступ = m.group(1)
        return (отступ + 'set _ЖДУ=\n'
                + отступ + 'set /p _ЖДУ=  Для продолжения нажмите Enter...\n')
    return re.sub(r'^([ \t]*)pause[ \t]*\n', замена, t, flags=re.M)

# Скобка в тексте `echo` внутри блока `if (...)` закрывает блок, и остаток
# строки cmd пытается выполнить как команду. Живой случай:
#   if not exist ... (
#     echo   Распакуйте архив (правой кнопкой - "Извлечь все") и повторите.
# дал «Непредвиденное появление: и.» и обвалил весь установщик на середине.
# Отслеживать глубину блоков вручную бессмысленно — после `echo ` всё до конца
# строки является текстом, и экранировать скобки там безопасно всегда,
# независимо от вложенности. Поэтому делаем это механически.
def экранировать_скобки(t):
    out = []
    for строка in t.split('\n'):
        голая = строка.lstrip()
        if голая.lower().startswith('echo ') and ('(' in строка or ')' in строка):
            отступ = строка[:len(строка) - len(голая)]
            слово, текст = голая.split(' ', 1)
            текст = текст.replace('^(', '(').replace('^)', ')')
            текст = текст.replace('(', '^(').replace(')', '^)')
            строка = отступ + слово + ' ' + текст
        out.append(строка)
    return '\n'.join(out)

def записать(имя, текст):
    путь = os.path.join(OUT, имя)
    готово = экранировать_скобки(под866(без_pause(текст)))
    # Ни одного символа не должно потеряться незаметно.
    плохие = sorted({c for c in готово if c not in '\n\r' and не_кодируется(c)})
    if плохие:
        raise SystemExit('не кодируются в cp866: ' + ' '.join(f'{c!r}(U+{ord(c):04X})' for c in плохие))
    # \r\n — обязательны: cmd.exe с чистыми \n в некоторых конструкциях
    # (метки, многострочные блоки) ведёт себя непредсказуемо.
    данные = готово.replace('\n', '\r\n').encode('cp866')
    # Круговая проверка: то, что прочтёт cmd.exe, обязано совпасть с исходником.
    assert данные.decode('cp866').replace('\r\n', '\n') == готово, 'круг не сошёлся: ' + имя
    io.open(путь, 'wb').write(данные)
    print('записан', имя, len(данные), 'байт (cp866), круговая проверка пройдена')

def не_кодируется(c):
    try:
        c.encode('cp866'); return False
    except UnicodeEncodeError:
        return True


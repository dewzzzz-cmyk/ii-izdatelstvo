// Авторские правки как сигнал качества.
//
// Единственный надёжный судья в этой цепочке — автор, и до сих пор ни одно его
// решение не возвращалось в систему. Оценщик судит, Стражи придираются, цикл
// доработки крутится вокруг балла — а балл, как показали замеры сессии, сцену
// по брифу с настоящим выбором оценил НИЖЕ, чем сцену, где герой ничего не
// решает, и ставит одну и ту же шестёрку за «Свежесть» нашей прозе, Чехову и
// Бунину. При собственном шуме судьи 0,5 и рабочем диапазоне 6,5–7,5 отношение
// сигнала к шуму около 2:1.
//
// При этом настоящий критерий качества у автора уже есть — он просто
// выбрасывается. Когда автор переписывает абзац, он одновременно говорит, что
// было не так и как выглядит правильно, причём своим голосом. Здесь мы это
// ловим и отдаём Прозаику: «вот что автор за тобой уже исправлял — не
// повторяй». Это не машинное обучение, а самая простая форма памяти о вкусе.

// Сколько пар держим. Правки копятся всю книгу, а в промпт уходят последние —
// вкус автора важнее в свежих сценах, чем в тех, что он правил месяц назад.
const MAX_ПАР = 40;
// Обрезка каждой стороны. Абзац длиннее — это уже не точечная правка, а
// переписанная сцена: её в промпт целиком тащить бессмысленно и дорого.
const MAX_ЗНАКОВ = 400;

function абзацы(t){
  return String(t||'').split(/\n\s*\n/).map(s=>s.trim()).filter(Boolean);
}

// Похожесть по символам, без токенизации: нужно отличить правку смысла от
// исправления опечатки, а не измерять семантику.
function похожесть(a, b){
  if(a === b) return 1;
  const дл = Math.max(a.length, b.length);
  if(!дл) return 1;
  // Расстояние считаем по общему префиксу и суффиксу — полноценный Левенштейн
  // на абзацах в 400 знаков не нужен и заметно дороже.
  let п = 0; while(п < a.length && п < b.length && a[п] === b[п]) п++;
  let с = 0; while(с < a.length-п && с < b.length-п && a[a.length-1-с] === b[b.length-1-с]) с++;
  const разное = дл - п - с;
  return Math.max(0, 1 - разное / дл);
}

// Выравнивание по НЕТРОНУТЫМ абзацам, а не по похожести текста.
//
// Первая редакция искала замену по близости строк и на настоящей правке
// провалилась: «Он очень сильно расстроился и долго не мог успокоиться» →
// «Он три раза перечитал одну и ту же строку» дают близость 0,07, и пара
// записалась как «абзац выброшен». А это ровно тот случай, ради которого всё
// и затевалось — замена объяснения чувства на наблюдаемое действие.
//
// Причина в том, что переписанный абзац с исходным почти не пересекается — ни
// по префиксу, ни по словам. Единственный надёжный признак того, что абзац Б
// заменил абзац А, — их ПОЛОЖЕНИЕ между неизменёнными соседями. Их в обычной
// правке большинство, и они работают якорями.
export function diffАбзацы(before, after){
  const A = абзацы(before), B = абзацы(after);
  // Якоря — абзацы, встречающиеся в обеих версиях ровно по одному разу:
  // повторяющийся абзац (рефрен, реплика-эхо) якорем быть не может, он бы
  // сбил выравнивание.
  const счёт = (arr) => arr.reduce((m,x)=>m.set(x,(m.get(x)||0)+1), new Map());
  const cA = счёт(A), cB = счёт(B);
  const якорь = t => cA.get(t) === 1 && cB.get(t) === 1;

  const пары = [];
  let i = 0, j = 0;
  const блок = ()=>{
    // Всё от текущей позиции до следующего якоря — то, что автор тронул.
    const доA = []; while(i < A.length && !якорь(A[i])) доA.push(A[i++]);
    const доB = []; while(j < B.length && !якорь(B[j])) доB.push(B[j++]);
    // Внутри блока сопоставляем по порядку: первый переписанный абзац стал
    // первым, второй — вторым. Хвост с любой стороны — удаление или добавление.
    const n = Math.max(доA.length, доB.length);
    for(let k = 0; k < n; k++){
      const было = доA[k], стало = доB[k];
      if(!было) continue;                                   // чистое добавление — учить нечему
      пары.push({ было, стало: стало || '', близость: стало ? похожесть(было, стало) : 0 });
    }
  };
  while(i < A.length || j < B.length){
    if(i < A.length && j < B.length && A[i] === B[j] && якорь(A[i])){ i++; j++; continue; }
    const доI = i, доJ = j;
    блок();
    if(i === доI && j === доJ){ i++; j++; }   // страховка от зацикливания
  }
  return пары;
}

// Правка опечатки ничему Прозаика не учит, а место в промпте занимает.
// Порог 0.9 отсекает замену слова и пунктуацию, оставляя переписанные фразы.
function значимая(п){
  if(!п.было) return false;
  if(п.стало === '') return п.было.length >= 40;      // выброшенный абзац — сигнал
  return п.близость < 0.9;
}

const обрезь = s => {
  const t = String(s||'').trim();
  return t.length > MAX_ЗНАКОВ ? t.slice(0, MAX_ЗНАКОВ) + '…' : t;
};

// Вызывается при фиксации ручной правки сцены (blur редактора). Возвращает
// число записанных пар — вызывающему это нужно, чтобы сказать автору, что его
// правка учтена, а не молча проглочена.
export function captureAuthorEdit(state, scene, before, after){
  if(!state || !scene) return 0;
  if(!before || !after || before === after) return 0;
  const пары = diffАбзацы(before, after).filter(значимая);
  if(!пары.length) return 0;
  state.memory = state.memory || {};
  const список = state.memory.authorEdits = state.memory.authorEdits || [];
  пары.forEach(п=>{
    список.push({
      at: Date.now(),
      sceneId: scene.id,
      sceneTitle: scene.title || '',
      было: обрезь(п.было),
      стало: обрезь(п.стало),
    });
  });
  // Кап держим на общем списке, а не на порции: иначе одна большая правка
  // вытеснила бы всю накопленную историю вкуса разом.
  if(список.length > MAX_ПАР) список.splice(0, список.length - MAX_ПАР);
  return пары.length;
}

// Блок для промпта Прозаика. limit небольшой сознательно: это подсказка о
// вкусе, а не досье — длинный блок вытеснит из окна бриф и канон, ради которых
// сцена и пишется.
export function authorEditsBlock(state, limit = 6){
  const список = state?.memory?.authorEdits || [];
  if(!список.length) return '';
  const свежие = список.slice(-limit);
  const строки = свежие.map(п => п.стало
    ? `— было: «${п.было}»\n  автор переписал на: «${п.стало}»`
    : `— автор ВЫБРОСИЛ этот абзац целиком: «${п.было}»`);
  return 'АВТОР УЖЕ ПРАВИЛ ЗА ТОБОЙ. Ниже его собственные исправления в предыдущих сценах этой книги — это прямое указание на то, что он считает плохим и что хорошим. Не повторяй того, что он вычеркнул, и держись того, как он переписал.\n'
    + строки.join('\n')
    + '\nНе копируй эти фразы дословно — они из других сцен. Перенимай ПРИЁМ: что автор убирает (объяснения, ярлыки чувств, лишние связки) и чем заменяет (действие, конкретная деталь, реплика).';
}

// Для интерфейса: сколько правок накоплено и по скольким сценам.
export function authorEditsStats(state){
  const список = state?.memory?.authorEdits || [];
  return { всего: список.length, сцен: new Set(список.map(x=>x.sceneId)).size };
}

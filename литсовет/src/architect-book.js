// Список глав уходит в промпт как данные. Собственный текст автора («turn»
// пишет модель, но названия глав при «улучшении» приходят из прежнего скелета,
// куда автор мог руками вписать что угодно) не должен уметь оборвать блок и
// выдать себя за инструкцию.
function списокБезопасно(s){
  return String(s||'').replace(/```/g, '`​`​`');
}

// Модель почти всегда сама префиксует название («Глава 4: Возвращение в
// Пустошь»), поэтому сравнивать заголовки как есть бесполезно — три одинаковые
// главы отличались бы только номером в префиксе.
function ядроНазвания(t){
  return String(t||'')
    .replace(/^\s*(пролог|эпилог|глава|часть|акт)\s*\d*\s*[:.—-]?\s*/i, '')
    .replace(/[«»"'.,!?…]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

// Одинаково названные главы. Возвращает группы, а не булев флаг: в сообщении
// об ошибке нужны номера глав, иначе автор не поймёт, где искать.
export function findDuplicateChapterTitles(chapters){
  // Номера — те же, что автор видит в интерфейсе: рамочные главы в счёт не
  // идут. Иначе сообщение противоречит само себе — заголовок «Глава 4», а
  // номера «5, 7, 14», потому что позицию сдвинул пролог.
  let n = 0;
  const по = new Map();
  (chapters||[]).forEach((ch)=>{
    const рамка = FRAME_ARCS.has(ch.arc);
    if(!рамка) n++;
    const ключ = ядроНазвания(ch.title);
    if(!ключ) return;
    if(!по.has(ключ)) по.set(ключ, { title: ch.title, numbers: [] });
    по.get(ключ).numbers.push(рамка ? (ch.arc||'рамка') : n);
  });
  return [...по.values()].filter(g => g.numbers.length > 1);
}

// Глава, названная именем своей же дуги («Кульминация», «Развязка», «Завязка»).
// Пролог и эпилог — исключение и даже требование: FRAME_CHAPTERS_NOTE прямо
// велит называть рамочные главы этими словами, потому что читатель ждёт их
// в оглавлении.
export function titleIsArcLabel(title, arc){
  if(FRAME_ARCS.has(arc)) return false;
  const ядро = ядроНазвания(title);
  return ['завязка','развитие','кульминация','развязка'].includes(ядро);
}

// Замер на живом скелете (69 брифов): формулировку выбора Архитектор ставит
// почти везде (48 из 69), а КОНКРЕТНУЮ цену — только в 16. Остальное сползает
// в пересказ: «Даня узнаёт, что…», «Он решает расследовать», «Он побеждает
// вора и возвращает воспоминания». BRIEF_CHOICE_NOTE это запрещает прямым
// текстом, но проверять инструкцию после генерации было некому.
// Мягкая проверка (не отбраковка): «пересказ» — это оценочное суждение, и
// хардблок по регуляркам был бы тиранией. Автору показываем список, решает он.
const ПАССИВ = ['узна','ему говор','ему сообщ','объясня','рассказыва','показыва','сообщает','слушает','соглашается'];
const ЦЕНА   = ['риск','цена','ценой','потеря','потеря','лишит','лишись','заплат','жертв','утрат','грозит','ставк','придётся отдать','придется отдать'];

export function findWeakBriefs(scenes){
  return (scenes||[]).map((sc,i)=>{
    const b = String(sc.brief||'').toLowerCase();
    if(!b) return null;
    const пассив = ПАССИВ.some(w=>b.includes(w));
    const цена   = ЦЕНА.some(w=>b.includes(w));
    if(пассив && !цена) return { index:i, id:sc.id, title:sc.title||'', chapterId:sc.chapterId };
    return null;
  }).filter(Boolean);
}

export function validateSkeleton(raw, opts={}){
  let j = extractJSON(raw);
  if(!j) return { ok:false, error:'не удалось распарсить JSON' };
  // Модель иногда оборачивает ответ: { "skeleton": {...} } или { "data": {...} }
  if(!Array.isArray(j.chapters)){
    const nested = Object.values(j).find(v => v && Array.isArray(v.chapters));
    if(nested) j = nested;
  }
  if(!Array.isArray(j.chapters) || !j.chapters.length){
    return { ok:false, error:'нет массива chapters' };
  }
  const chapters = j.chapters.map(normalizeChapterRaw).filter(Boolean);
  if(!chapters.length) return { ok:false, error:'ни одной валидной главы со сценами' };

  // ── Целостность распределения сцен по главам ──
  // Живой прогон: скелет приняли как корректный, хотя главы вышли 4/4/4/1, а
  // нумерация в собственных названиях модели прыгнула со «Сцены 12» на «Сцену
  // 15» — две сцены просто не доехали, и последняя глава осталась огрызком с
  // одной сценой. Ни одной проверки на это не было: достаточно было, чтобы у
  // каждой главы нашлась хотя бы одна сцена. Автор получал книгу с оборванным
  // финалом, ничего об этом не зная.
  // Ошибку возвращаем, а не «подчищаем» молча: цикл повторов в runBookArchitect
  // уже умеет перезапросить скелет (и с 1.38.0 поднимает при этом лимит), то
  // есть у нас есть рабочий способ получить целый скелет вместо кривого.
  const counts = chapters.map(ch=>ch.scenes.length);
  const maxCount = Math.max(...counts);
  // Порог сознательно мягкий: короткая финальная глава — законный авторский приём.
  // Ловим именно вырожденный случай — глава меньше трети самой большой при том,
  // что большая содержит 3+ сцены (иначе на книге из 2-сценовых глав ложные срабатывания).
  if(maxCount >= 3){
    // Пролог и эпилог из этой проверки исключены: одна сцена в рамочной главе —
    // норма жанра, а не потерянные сцены. Без исключения книга с прологом
    // отбраковывалась бы как «часть сцен не доехала» и перезапрашивалась
    // платно, пока модель не выбросит пролог.
    const idx = counts.findIndex((c,i) => c * 3 < maxCount && !FRAME_ARCS.has(chapters[i].arc));
    if(idx >= 0){
      return { ok:false, error:`глава ${idx+1} содержит ${counts[idx]} сцен(ы) против ${maxCount} у самой полной — похоже, часть сцен не доехала` };
    }
  }
  // Недовоз по общему числу сцен: если промпт просил N, а пришло меньше 70%,
  // это тот же обрыв, просто заметный не по одной главе, а по сумме.
  const total = counts.reduce((a,b)=>a+b, 0);
  const want = Number(opts.expectedScenes) || 0;
  if(want >= 6 && total < Math.round(want * 0.7)){
    return { ok:false, error:`сцен всего ${total} при запрошенных ~${want} — скелет пришёл неполным` };
  }
  // ── Признаки выдохшегося Архитектора ──
  // Живой скелет 18 глав по завязке в 45 слов: три главы подряд назывались
  // «Возвращение в Пустошь», а последние две — «Кульминация» и «Развязка», то
  // есть модель назвала главы именами их же слотов, потому что сюжет кончился,
  // а слоты остались. Оценщик структуры это ловил постфактум (6.2 балла и
  // десять замечаний), но автор к тому моменту уже заплатил за генерацию и
  // читал скелет глазами. Проверка детерминированная и бесплатная — и она,
  // в отличие от уговоров в промпте, не зависит от того, послушалась ли модель.
  const дубли = findDuplicateChapterTitles(chapters);
  if(дубли.length){
    return { ok:false, kind:'content', error:`главы ${дубли[0].numbers.join(', ')} названы одинаково («${дубли[0].title}») — Архитектор ходит по кругу вместо того, чтобы двигать сюжет` };
  }
  const слот = chapters.findIndex(ch => titleIsArcLabel(ch.title, ch.arc));
  if(слот >= 0){
    const номер = chapters.slice(0, слот+1).filter(c=>!FRAME_ARCS.has(c.arc)).length;
    return { ok:false, kind:'content', error:`глава ${номер} названа «${chapters[слот].title}» — это имя слота структуры, а не название главы: у Архитектора кончился сюжет` };
  }
  return { ok:true, skeleton:{ chapters } };
}

// Валидация ответа ТОЧЕЧНОЙ правки (bookArchitectPatchMessages) — модель
// обязана вернуть только главы из allowedNumbers (1-based позиция главы в
// текущей книге), помеченные полем "number". Контекстные главы, которые ей
// показали для стыка ритма, но просили не редактировать, отфильтровываются
// здесь же — если модель всё равно их вернула, просто игнорируем.
export function validateSkeletonPatch(raw, allowedNumbers){
  let j = extractJSON(raw);
  if(!j) return { ok:false, error:'не удалось распарсить JSON' };
  if(!Array.isArray(j.chapters)){
    const nested = Object.values(j).find(v => v && Array.isArray(v.chapters));
    if(nested) j = nested;
  }
  if(!Array.isArray(j.chapters) || !j.chapters.length){
    return { ok:false, error:'нет массива chapters' };
  }
  const allowed = new Set(allowedNumbers);
  const chapters = [];
  for(const ch of j.chapters){
    const number = Number(ch && ch.number);
    if(!allowed.has(number)) continue;
    const norm = normalizeChapterRaw(ch);
    if(norm) chapters.push({ number, ...norm });
  }
  if(!chapters.length) return { ok:false, error:'ни одной валидной главы из запрошенных номеров' };
  return { ok:true, chapters };
}

// Запуск с ретраем при невалидном JSON (спека 11: кривой JSON ломает пайплайн).
export async function runBookArchitect(state, opts={}){
  const g = state.global;
  const architectAgent = ag(state, 'bookArchitect');
  // Ключ проверяем через llmFor (учитывает per-роль override bookArchitect,
  // используемый ниже в callLLM), не голый global.apiKey — тот же класс бага,
  // что уже чинили в ondemand.js/llmFor().
  if(!llmFor(state, architectAgent).apiKey) throw new Error('Не задан API-ключ.');
  // ~140 токенов на сцену (русский бриф 1-2 предложения + поля) + накладные
  const p = state.project;
  // Та же формула wPerScene, что и в bookArchitectMessages — иначе при явном
  // project.sceneWords здесь получим СТАРОЕ (меньшее) число сцен, а промпт
  // попросит модель сгенерировать БОЛЬШЕЕ — и archMaxTokens окажется занижен,
  // провоцируя обрезание JSON именно тогда, когда включён sceneWords.
  const wPerScene = p.sceneWords>0
    ? Math.max(300, Math.min(4000, p.sceneWords))
    : (ageSceneWords(p.ageGroup) || Math.max(700, Math.min(2000, Math.round((p.targetWords||80000)/60))));
  const targetScenes = Math.max(6, Math.round((p.targetWords||80000) / wPerScene));
  // При «Улучшении» формула-предсказание может недооценить фактический размер
  // книги — живой пример: формула по общему объёму предсказала 60 сцен
  // (9900 ток. бюджета), а книга уже реально разрослась до 47 сцен с
  // РАЗВЁРНУТЫМИ брифами (2-3 предложения, не черновые 1-2, как при первой
  // генерации — сама инструкция «улучши» требует сохранить детализацию, не
  // урезать её). 9900 токенов не хватило, JSON обрывался на середине и не
  // парсился. Берём максимум из формулы и фактического числа сцен, и щедрее
  // считаем токены на сцену именно для improve (там брифы длиннее черновых).
  const prevSceneCountForBudget = opts.previousSkeleton
    ? opts.previousSkeleton.chapters.reduce((n,ch)=>n+(ch.scenes||[]).length, 0) : 0;
  const effectiveScenes = Math.max(targetScenes, prevSceneCountForBudget);
  // 140/250 → 220/300: то же самое обрезание JSON (см. комментарий выше про
  // 9900 токенов на 60 сцен), но теперь и на ПЕРВОЙ генерации без previousSkeleton
  // — после того как в схему сцены добавили entryState (см. записи сессии про
  // «непрерывность знаний героя»), каждая сцена стала на одно поле длиннее, а
  // константу 140 для свежей генерации не подняли вместе с ней. Живой инцидент:
  // 60 сцен × 140 = 9900 ток. бюджета, реальный ответ обрезался на ~31870
  // символах (≈3.2 симв/ток на этой модели) не дойдя до конца JSON.
  // 220/300 → 420/480. Замерено на живом прогоне (реальный ключ, 4-5 глав):
  // бюджет вышел 5760 ток., и ДВЕ попытки подряд обрубились ровно на потолке
  // (17 130 и 17 115 символов ≈ 2.97 симв/ток на этой модели), обе легли в
  // «не удалось распарсить JSON». Третья прошла только потому, что модель
  // случайно написала лаконичнее — 599 символов на бриф против 842 в
  // предыдущем прогоне. Фактический расход успешной попытки: 18 сцен, 14 316
  // символов JSON ≈ 318 ток./сцену при заложенных 220, то есть запаса не было
  // вообще, и попадание в лимит решала случайность формулировок.
  // Причина роста: BRIEF_DETAIL_NOTE требует бриф в 3-4 предложения с
  // сенсорной деталью, плюс entryState, плюс ARC_DISTRIBUTION_NOTE — схема
  // сцены выросла, а константа осталась от более коротких брифов.
  // 420 берём с запасом над замеренными 318 (verbose-попытки просили ~380),
  // improve-режим 480 — там брифы заведомо длиннее черновых.
  // Цена ошибки была не только в деньгах: каждая неудачная попытка — это ~60
  // секунд ожидания, отсюда и «структура формируется слишком долго» (188 с на
  // три попытки против ~60 с на одну).
  const perSceneTokens = opts.previousSkeleton ? 480 : 420;
  // +20% по запросу автора (общий проход по всем лимитам токенов приложения),
  // потолок поднят 30000→40000, и сверху ещё множитель из настроек автора
  // (state.global.architectTokenMultiplier, слайдер «Запас токенов» у роли
  // bookArchitect в ui/diagnostics.js) — обычный maxTokens-слайдер этой роли
  // не показываем (сломал бы авто-масштабирование по объёму книги), но автор
  // должен иметь ручку «дать ещё больше места», не дожидаясь очередного
  // ручного бампа константы в коде при каждой новой длинной книге.
  const archMult = state.global.architectTokenMultiplier || 1;
  // Единого потолка на всю книгу больше нет — лимит считается на КАЖДЫЙ запрос
  // (список глав и пачка глав) ниже. Множитель автора применяется к обоим.
  // Лимит РАСТЁТ между попытками, если ответ обрубило. Раньше повтор уходил с
  // тем же самым archMaxTokens и лишь просил модель «верни полный JSON» — но
  // упирается-то не модель, а потолок: живой прогон дал две попытки подряд,
  // обрубленные на одинаковой длине, и обе бесполезно потратили ~60 секунд и
  // деньги. Просить «будь полнее» при неизменном лимите нельзя в принципе.
  // Тот же приём «повтор с увеличенным лимитом», что уже стоит у Прозаика,
  // Оценщика, Стражей и пер-сценового Архитектора — здесь его не было.
  // Живой инцидент: автор видел «спиннер навсегда» на скелете из 47+ сцен —
  // единственный вызов callLLM во всём приложении без onToken (см. остальные
  // сайты в pipeline.js), хотя именно тут самый большой maxTokens (до 30000) и
  // реально самая долгая генерация. Без чанков не отличить «ещё стримит» от
  // «висит» — 5+ минут молчания читались как зависание, хотя апстрим отвечал.
  // retries тоже не пробрасывался в callLLM (падало на дефолт 2), в отличие от
  // всех остальных сайтов — тот же класс бага «пропущено в одном пути».
  let streamedChars = 0;
  const onChunk = chunk=>{ streamedChars += chunk.length; opts.onChunk && opts.onChunk(streamedChars); };
  // Живой инцидент: «Книжный архитектор вернул невалидный скелет: не удалось
  // распарсить JSON» — и ни единой зацепки, ЧТО именно модель вернула. В
  // отличие от Оценщика/Прозаика (у них есть logStep на каждой попытке),
  // runBookArchitect вообще ни разу не писал в diagnostics.runs — ни успешные,
  // ни провальные попытки. Отладить конкретный случай было нечем: тот же
  // класс пробела, что уже чинили для Оценщика (см. evaluator-retry), только
  // здесь не хватало не ретрая, а самого факта логирования.
  startRun(null, 'Книжный архитектор');

  // Общий цикл повторов для обоих проходов. Раньше он был вписан прямо в тело
  // runBookArchitect и обслуживал единственный запрос; теперь запросов много
  // (один на список глав + по одному на пачку глав), и копировать эту логику
  // в каждый — ровно тот класс бага «починили в одном пути, забыли в соседнем»,
  // который в этом файле уже ловили не раз.
  async function askWithRetries({ label, messages, maxTokens, validate, contentHint }){
    let msgsLocal = messages.slice();
    let limit = maxTokens;
    let lastError = '';
    for(let attempt=0; attempt<=(g.retries??2); attempt++){
      const res = await callLLM({ ...llmFor(state,architectAgent), temperature:architectAgent.temp??0.6, messages:msgsLocal, maxTokens:limit }, onChunk);
      const v = validate(res.text);
      logStep({ agent:'bookArchitect', iter:attempt+1, input:`(${label}, лимит ${limit})`, output:res.text,
        tokensIn:res.tokensIn, tokensOut:res.tokensOut, cost:res.cost, verdict:{ ok:v.ok, error:v.ok?undefined:v.error } });
      if(v.ok) return v;
      lastError = v.error;
      const текст = (res.text||'').trim();
      const preview = текст.slice(0, 120).replace(/\n/g,' ');
      if(текст.endsWith('"') || текст.endsWith(',') || !текст.endsWith('}')){
        // Обрыв — следующей попытке нужно БОЛЬШЕ места, а не просьба «будь полнее»:
        // при неизменном лимите она упрётся в тот же потолок.
        limit = Math.min(200000, Math.round(limit * 1.6));
        msgsLocal = msgsLocal.concat([{ role:'user', content:`JSON обрезан (ответ не закончен). Повтори запрос: верни ТОЛЬКО полный JSON-объект с chapters, без пояснений.` }]);
      } else if(v.kind === 'content'){
        // JSON пришёл целым — беда в содержании, и просьба «верни строго JSON»
        // здесь только путает: формат был в порядке.
        msgsLocal = msgsLocal.concat([{ role:'user', content:`Отклонено: ${v.error}. Формат JSON был в порядке — переделай СОДЕРЖАНИЕ. ${contentHint} Верни полный JSON заново.` }]);
      } else {
        msgsLocal = msgsLocal.concat([{ role:'user', content:`Ответ невалиден (${v.error}). Начало ответа: «${preview}». Верни СТРОГО JSON {"chapters":[...]} без лишнего текста.` }]);
      }
    }
    throw new Error(lastError || 'не удалось получить валидный ответ');
  }

  try{
    // ── ПРОХОД 1: только список глав ──
    // ~120 токенов на главу (название + дуга + одно предложение поворота).
    // Число глав берём из уже посчитанного здесь targetScenes — отдельная
    // копия формулы объёма сцены была бы четвёртой в файле и неминуемо
    // разъехалась бы с остальными (ровно это и стережёт инвариант-тест).
    const prevChapterCount = opts.previousSkeleton ? opts.previousSkeleton.chapters.length : 0;
    const targetChaptersRun = opts.chapters || prevChapterCount || Math.max(3, Math.min(25, Math.round(targetScenes / 3.5)));
    const outlineTokens = Math.round(Math.max(1500, targetChaptersRun * 160 + 800) * archMult);
    const ov = await askWithRetries({
      label: 'список глав',
      messages: bookArchitectMessages(state, { ...opts, outlineOnly:true }),
      maxTokens: outlineTokens,
      validate: raw => validateOutline(raw),
      contentHint: 'Одинаковых названий и глав-наполнителей быть не должно: если сюжет упирается в повтор, СОКРАТИ число глав и укрупни события. Вернуть меньше глав, чем запрошено, — разрешено.',
    });
    const outline = ov.outline;
    opts.onOutline && opts.onOutline(outline);

    // ── ПРОХОД 2: сцены по главам, пачками ──
    // Пачку подбираем так, чтобы один ответ оставался в разумных пределах
    // (~12 сцен): именно объём одного ответа и был причиной, по которой модель
    // теряла из виду начало книги.
    const сценНаГлаву = Math.max(2, Math.round(effectiveScenes / Math.max(1, outline.chapters.length)));
    const главВПачке = Math.max(1, Math.min(6, Math.round(12 / сценНаГлаву)));
    const собранные = new Map();
    const доСих = [];
    for(let from=0; from<outline.chapters.length; from+=главВПачке){
      const to = Math.min(outline.chapters.length, from + главВПачке);
      const номера = [];
      for(let i=from; i<to; i++) номера.push(i+1);
      const bv = await askWithRetries({
        label: `сцены глав ${номера.join(', ')}`,
        messages: bookArchitectMessages(state, { ...opts, forChapters:{ outline, from, to, doneScenes: доСих.slice(-24) } }),
        maxTokens: Math.round(Math.max(3000, (to-from) * сценНаГлаву * perSceneTokens * 1.3) * archMult),
        validate: raw => validateSceneBatch(raw, номера),
        contentHint: 'Верни сцены для КАЖДОЙ перечисленной главы, с полем number.',
      });
      номера.forEach(n=>{
        const scenes = bv.byNumber.get(n);
        собранные.set(n, scenes);
        const c = outline.chapters[n-1];
        scenes.forEach(s=>доСих.push(`гл.${n} «${c.title}» → «${s.title}»`));
      });
      opts.onProgress && opts.onProgress(to, outline.chapters.length);
    }

    // ── Сборка и финальная проверка ──
    // Собранный скелет проходит ТУ ЖЕ validateSkeleton, что и одноразовая
    // генерация: правила про огрызки глав, дубли названий и главы-слоты должны
    // работать одинаково, каким бы способом скелет ни получили.
    const assembled = { chapters: outline.chapters.map((c,i)=>({
      title: c.title, arc: c.arc, scenes: собранные.get(i+1) || [],
    })).filter(c=>c.scenes.length) };
    const fv = validateSkeleton(JSON.stringify(assembled), { expectedScenes: effectiveScenes });
    if(!fv.ok) throw new Error(fv.error);

    endRun('done');
    // Нормализация targetWords: база = totalWords / фактич. число сцен.
    const allScenes = fv.skeleton.chapters.flatMap(ch=>ch.scenes||[]);
    const norm = p.sceneWords>0
      ? Math.max(300, Math.min(4000, p.sceneWords))
      : Math.max(700, Math.min(2000, Math.round((p.targetWords||80000)/Math.max(1,allScenes.length))));
    const minW = Math.round(norm * 0.80);
    const maxW = Math.round(norm * 1.20);
    allScenes.forEach(sc=>{
      const tw = Number(sc.targetWords)||0;
      // Симметрично верхнему краю: клэмп в minW, а не в norm — иначе намеренно
      // короткая переходная сцена принудительно раздувалась до среднего объёма.
      if(tw < minW) sc.targetWords = minW;
      else if(tw > maxW) sc.targetWords = maxW;
    });
    return fv.skeleton;
  }catch(e){
    endRun('error');
    throw new Error(`Книжный архитектор вернул невалидный скелет: ${e.message}`);
  }
}


// ── Точечная правка скелета (structurePatchMode) ──
// Вместо пересборки ВСЕЙ книги (bookArchitectMessages — даже нетронутые главы
// неизбежно немного переписываются моделью при temp 0.6, что и уронило балл
// на живом прогоне на «Разломе»: 4 проблемы 3 итерации подряд помечались
// «не устранено», хотя формулировки сцен каждый раз менялись) — отдаём модели
// ТОЛЬКО главы, которые Оценщик назвал в affectedChapters, плюс по одной
// соседней с каждого края КАК КОНТЕКСТ (не редактировать — нужен только чтобы
// модель видела стык ритма сцена/секвель на границе). Все остальные главы,
// включая уже написанные сцены, вообще не попадают в запрос.
export function bookArchitectPatchMessages(state, { affectedChapters, hint }){
  const p = state.project;
  const chapterNodes = (state.structure||[]).filter(n=>n.type==='chapter');
  const structure = state.structure||[];
  const targets = new Set(affectedChapters);
  const contextOnly = new Set();
  affectedChapters.forEach(n=>{
    if(n-1>=1 && !targets.has(n-1)) contextOnly.add(n-1);
    if(n+1<=chapterNodes.length && !targets.has(n+1)) contextOnly.add(n+1);
  });
  const wanted = [...targets, ...contextOnly].sort((a,b)=>a-b);

  const wPerScene = p.sceneWords>0
    ? Math.max(300, Math.min(4000, p.sceneWords))
    : (ageSceneWords(p.ageGroup) || Math.max(700, Math.min(2000, Math.round((p.targetWords||80000)/60))));
  const wMin = Math.round(wPerScene*0.80), wMax = Math.round(wPerScene*1.20);

  const sys = [
    'Ты — книжный архитектор. Тебе показан ФРАГМЕНТ скелета книги — несколько глав, не вся книга.',
    `Перепроектируй ТОЛЬКО главы с номерами: ${affectedChapters.join(', ')}. Главы с пометкой «(КОНТЕКСТ — НЕ редактировать)» показаны только чтобы ты видел стык ритма сцена/секвель на границе — не включай их в ответ и не меняй.`,
    `Базовый объём сцены: ${wPerScene} слов. Диапазон: ${wMin}–${wMax} слов (±20%). НЕ выходи за пределы.`,
    'Классифицируй КАЖДУЮ сцену по sceneType (техника Дуайта Свейна):',
    '  "scene" — сцена действия: цель героя → конфликт/препятствие → поражение или осложнение. Растущее напряжение.',
    '  "sequel" — секвель: реакция героя на произошедшее → дилемма → решение, ставящее новую цель. Передышка, меньше внешнего действия.',
    genreWantsHumor(p.genre)
      ? 'Ирония жанра касается ВСЕХ сцен, не только явно магических/жанровых — сохраняй приём снижения пафоса и там, где он не был явно указан раньше.'
      : '',
    'entryState: заполняй ТОЛЬКО когда на входе в сцену у героя появилось что-то новое (предмет, знание, место, союзник), не установленное в предыдущей сцене — что именно и откуда. Смотри «[на входе: ...]» у контекстных и целевых сцен ниже — не противоречь уже установленной цепочке знаний на стыке с непатченными главами.',
    KNOWLEDGE_CONTINUITY_NOTE,
    BRIEF_DETAIL_NOTE,
    BRIEF_CHOICE_NOTE,
    PACING_NOTES[p.pacing] || PACING_NOTES.balanced,
    // Правило дуг и здесь (см. ARC_DISTRIBUTION_NOTE у полной генерации): точечная
    // правка тоже возвращает поле arc, а Оценщик структуры может прислать именно
    // «кульминация смещена»/«финал не подготовлен» как affectedChapters. Формулировка
    // фрагмент-осознанная: модель видит не всю книгу, поэтому даём ей номера явно.
    `ДУГИ (arc): в книге всего ${chapterNodes.length} глав. Глава 1 — «завязка», глава ${chapterNodes.length} — «развязка», одна глава ближе к концу — «кульминация», остальные — «развитие». Ставь arc правимым главам по их номеру в этой схеме, а не «развитие» по умолчанию.`,
    // Морфология жанра нужна и точечной правке: без неё перегенерация главы
    // сказки возвращала главу маленького психологического романа — общая
    // четырёхактная схема выше сама по себе этого не запрещает.
    genreStructureNote(genresOf(p)),
    // Актуально только когда среди патчимых глав есть глава 1 — эта правка
    // не «изредка полезна», а обязательна: Оценщик структуры может явно
    // прислать «Ставки первой главы»/структурный провал именно в главе 1
    // как affectedChapters, и тогда без этой инструкции точечная правка
    // не знает, что у сцены 1.1 особые требования (нет предыдущего брифа).
    targets.has(1) ? FIRST_SCENE_NOTE : '',
  ].filter(Boolean).join('\n');

  // Тот же канон мира, что видит bookArchitectMessages (полная генерация) —
  // раньше точечная правка его вообще не получала: модель могла перепланировать
  // главу так, что новый бриф противоречил уже закреплённому факту мира,
  // который просто не был ей показан.
  const worldBlockPatch = bibleForPrompt((state.bible||[]).filter(b=>b.source==='world' || b.pinned), p.synopsis||p.idea||'', 15);

  const chText = wanted.map(n=>{
    const chNode = chapterNodes[n-1];
    const isTarget = targets.has(n);
    const scenes = structure.filter(s=>s.type==='scene' && s.chapterId===chNode.id);
    const scList = scenes.map((sc,si)=>`    ${n}.${si+1}. (${sc.sceneType==='sequel'?'секвель':'сцена'}) «${sc.title}» [${sc.targetWords||700}сл] — ${sc.brief||'(без брифа)'}${sc.entryState?` [на входе: ${sc.entryState}]`:''}`).join('\n');
    return `Глава ${n}${isTarget?'':' (КОНТЕКСТ — НЕ редактировать)'} [${chNode.arc||'?'}]: «${chNode.title}»\n${scList}`;
  }).join('\n\n');

  const user = [
    `Жанр: ${genresOf(p).join(' + ')||'роман'}${p.subgenre?', '+p.subgenre:''}.`,
    worldBlockPatch ? `МИР КНИГИ (уже зафиксированные факты — не противоречь им):\n${worldBlockPatch}\n${WORLD_USE_NOTE}` : '',
    'ФРАГМЕНТ СКЕЛЕТА:',
    chText,
    hint ? `\nПРОБЛЕМЫ ДЛЯ ИСПРАВЛЕНИЯ:\n${hint}` : '',
    '',
    `Верни ТОЛЬКО главы ${affectedChapters.join(', ')} (без контекстных), в том же порядке, в JSON:`,
    '{ "chapters": [ { "number": номер_главы, "title": "название главы", "arc": "пролог|завязка|развитие|кульминация|развязка|эпилог", "scenes": [ { "title": "название сцены", "brief": "3-4 предложения (см. БРИФ СЦЕНЫ выше): что происходит → ключевой конфликт или открытие → конкретная сенсорная деталь кульминационного момента → чем кончается и что изменилось", "emotion": "эмоция читателя в финале сцены", "entryState": "если на входе в сцену у героя уже есть предмет/знание/состояние, не самоочевидное из предыдущего брифа — одной строкой что и откуда; иначе пустая строка", "targetWords": число, "sceneType": "scene|sequel" } ] } ] }',
    'Брифы конкретные. Только JSON.',
  ].filter(Boolean).join('\n');

  return [{role:'system',content:sys},{role:'user',content:user}];
}

export async function runBookArchitectPatch(state, opts={}){
  const g = state.global;
  const architectAgent = ag(state, 'bookArchitect');
  // См. runBookArchitect выше: ключ через llmFor (per-роль override bookArchitect).
  if(!llmFor(state, architectAgent).apiKey) throw new Error('Не задан API-ключ.');
  const { affectedChapters } = opts;
  const msgs = bookArchitectPatchMessages(state, opts);
  // Бюджет только под затронутые главы — тот же тариф на сцену (300 ток.),
  // что и полный improve-режим в runBookArchitect (см. там про entryState —
  // одно поле длиннее, константу подняли вместе), но без раздутия под всю книгу.
  const chapterNodes = (state.structure||[]).filter(n=>n.type==='chapter');
  const structure = state.structure||[];
  const sceneCountInTargets = affectedChapters.reduce((n,num)=>{
    const chNode = chapterNodes[num-1];
    return chNode ? n + structure.filter(s=>s.type==='scene' && s.chapterId===chNode.id).length : n;
  }, 0);
  // +20% по запросу автора (общий проход по всем лимитам токенов приложения),
  // потолок поднят 12000→16000, и множитель из настроек (см. runBookArchitect).
  const maxTokens = Math.round(Math.max(2000, Math.min(16000, sceneCountInTargets*300 + 800)) * 1.2 * (g.architectTokenMultiplier || 1));
  let lastErr = '';
  // Тот же пробел, что был у runBookArchitect (см. её комментарий выше про
  // startRun/logStep) — точечная правка тоже ни разу не писала в diagnostics.
  startRun(null, 'Архитектор (точечная правка)');
  for(let attempt=0; attempt<=(g.retries??2); attempt++){
    const res = await callLLM({ ...llmFor(state,architectAgent), temperature:architectAgent.temp??0.6, messages:msgs, maxTokens });
    assertNotTruncated(res, 'Книжный архитектор');
    const v = validateSkeletonPatch(res.text, affectedChapters);
    logStep({ agent:'bookArchitectPatch', iter:attempt+1, input:`(правка глав ${affectedChapters.join(', ')}, лимит ${maxTokens})`, output:res.text,
      tokensIn:res.tokensIn, tokensOut:res.tokensOut, cost:res.cost, verdict:{ ok:v.ok, error:v.ok?undefined:v.error } });
    if(v.ok){ endRun('done'); return v.chapters; }
    lastErr = v.error;
    const preview = (res.text||'').slice(0, 120).replace(/\n/g,' ');
    msgs.push({ role:'user', content:`Ответ невалиден (${v.error}). Начало ответа: «${preview}». Верни СТРОГО JSON {"chapters":[{"number":...,...}]} только для глав ${affectedChapters.join(', ')}, без лишнего текста.` });
  }
  endRun('error');
  throw new Error(`Архитектор (точечная правка) вернул невалидный ответ: ${lastErr}`);
}

// Перегенерация ОДНОЙ сцены скелета с подсказкой автора о направлении.
// Видит соседние сцены и главу — чтобы вписаться в дугу. Возвращает поля сцены.
export async function regenerateScene(state, scene, hint){
  const g = state.global;
  // Раньше здесь напрямую читался state.global (apiKey/baseURL/model,
  // temperature жёстко 0.7) в обход персонального конфига роли «Книжный
  // архитектор» (провайдер/модель/ключ/температура — см. runBookArchitect чуть
  // выше по файлу, где llmFor(state, architectAgent) уже применяется). Точечная
  // перегенерация одной сцены — самый частый путь ручной правки — молча
  // использовала глобальный провайдер, даже если автор настроил Архитектору
  // отдельный. Тот же класс бага, что уже чинили для Прозаика (inline.js).
  const architectAgent = ag(state, 'bookArchitect');
  const llm = llmFor(state, architectAgent);
  if(!llm.apiKey) throw new Error('Не задан API-ключ.');
  const nodes = state.structure||[];
  const ch = nodes.find(n=>n.type==='chapter' && n.id===scene.chapterId);
  const scenes = nodes.filter(n=>n.type==='scene');
  const idx = scenes.findIndex(n=>n.id===scene.id);
  const prev = scenes[idx-1], next = scenes[idx+1];
  const p = state.project;
  // Тот же диапазон, что видит полная генерация/точечная правка (bookArchitectMessages/
  // bookArchitectPatchMessages) — раньше здесь модели вообще не называли числа,
  // targetWords вылезал за адекватный диапазон и его тихо ловил только clampSceneTargetWords
  // постфактум, без единого шанса у модели попасть в диапазон осознанно.
  const norm = p.sceneWords>0 ? Math.max(300, Math.min(4000, p.sceneWords))
    : Math.max(700, Math.min(2000, Math.round((p.targetWords||80000) / Math.max(1, scenes.length))));
  const wMin = Math.round(norm*0.80), wMax = Math.round(norm*1.20);
  const worldBlock = bibleForPrompt((state.bible||[]).filter(b=>b.source==='world' || b.pinned), p.synopsis||p.idea||'', 15);
  const sys = 'Ты — книжный архитектор. Перепроектируй ОДНУ сцену по подсказке автора, сохраняя её место в нарративной арке книги. Не пишешь прозу.';
  const user = [
    `Жанр: ${p.genre||'роман'}. Синопсис: ${p.synopsis||p.idea||''}`,
    worldBlock ? `МИР КНИГИ (уже зафиксированные факты — не противоречь им):\n${worldBlock}` : '',
    ch?`Глава: «${ch.title}» (${ch.arc||''}).`:'',
    prev?`Предыдущая сцена: «${prev.title}» — ${prev.brief}${prev.entryState?` [на входе: ${prev.entryState}]`:''}`:'',
    next?`Следующая сцена: «${next.title}» — ${next.brief}${next.entryState?` [на входе: ${next.entryState}]`:''}`:'',
    `Текущая сцена: «${scene.title}» — ${scene.brief}${scene.entryState?` [на входе: ${scene.entryState}]`:''}`,
    '',
    'ПОДСКАЗКА АВТОРА (в каком направлении переделать): ' + (hint||'сделай сильнее и конкретнее'),
    '',
    `targetWords — диапазон ${wMin}–${wMax} слов (±20% от базового объёма сцены ${norm}), не выходи за пределы.`,
    'entryState — заполняй ТОЛЬКО если на входе в сцену у героя появилось что-то новое (предмет/знание/место), не установленное в предыдущей сцене; не противоречь тому, что уже на входе следующей сцены. Если ничего не изменилось — пустая строка.',
    KNOWLEDGE_CONTINUITY_NOTE,
    // Актуально только когда переделываемая сцена — реально первая сцена книги
    // (нет prev): та же дыра, что чинили в bookArchitectPatchMessages — без
    // FIRST_SCENE_NOTE точечная перегенерация сцены 1 не знает про её особые
    // требования (нет предыдущего брифа, откуда унаследовать контекст).
    !prev ? FIRST_SCENE_NOTE : '',
    BRIEF_DETAIL_NOTE,
    BRIEF_CHOICE_NOTE,
    PACING_NOTES[p.pacing] || PACING_NOTES.balanced,
    'Верни JSON одной сцены: { "title":"…", "brief":"3-4 предложения (см. БРИФ СЦЕНЫ выше): что происходит → ключевой конфликт/открытие → конкретная сенсорная деталь кульминационного момента → чем кончается и что изменилось", "emotion":"эмоция читателя", "entryState":"см. выше", "targetWords":число, "sceneType":"scene|sequel" }. sceneType: "scene" — растущее напряжение (цель→конфликт→поражение), "sequel" — передышка (реакция→дилемма→решение). Только JSON.',
  ].filter(Boolean).join('\n');
  // Тот же пробел, что чинили у runBookArchitect/runBookArchitectPatch — точечная
  // перегенерация одной сцены не масштабировала лимит по architectTokenMultiplier
  // (слайдер «Запас токенов» роли bookArchitect) и не писала в diagnostics.runs,
  // хотя это самый частый путь ручной правки скелета.
  const maxTokens = Math.round(900 * 1.2 * (g.architectTokenMultiplier || 1));
  let lastErr='';
  startRun(null, 'Архитектор (перегенерация сцены)');
  for(let attempt=0; attempt<=(g.retries??2); attempt++){
    const res = await callLLM({ ...llm, temperature:architectAgent.temp??0.7, messages:[{role:'system',content:sys},{role:'user',content:user}], maxTokens });
    assertNotTruncated(res, 'Книжный архитектор');
    const j = extractJSON(res.text);
    logStep({ agent:'bookArchitectScene', iter:attempt+1, input:`(перегенерация сцены, лимит ${maxTokens})`, output:res.text,
      tokensIn:res.tokensIn, tokensOut:res.tokensOut, cost:res.cost, verdict:{ ok:!!(j && typeof j.brief==='string'), error:(j && typeof j.brief==='string')?undefined:'невалидный JSON' } });
    if(j && typeof j.brief==='string'){
      endRun('done');
      return {
        title:(j.title||scene.title).trim(),
        brief:j.brief.trim(),
        emotion:(j.emotion||scene.emotion||'').trim(),
        entryState:(typeof j.entryState==='string'?j.entryState:scene.entryState||'').trim(),
        targetWords: clampSceneTargetWords(state, Number(j.targetWords)>0?j.targetWords:(scene.targetWords||700)),
        sceneType: j.sceneType==='sequel' ? 'sequel' : 'scene',
      };
    }
    lastErr='невалидный JSON';
  }
  endRun('error');
  throw new Error('Не удалось перегенерировать: '+lastErr);
}

// Каскадная перегенерация ВСЕХ последующих сцен с учётом изменения текущей
// (когда поворот сюжета сделал хвост книги несогласованным). Сохраняет число
// сцен и привязку к главам; переписывает их брифы/эмоции консистентно.
export async function regenerateDownstream(state, pivotScene, hint){
  const g = state.global;
  // См. комментарий в regenerateScene выше — та же дыра (глобальный конфиг в
  // обход персонального провайдера/модели/ключа/температуры роли «Книжный
  // архитектор»), тот же фикс.
  const architectAgent = ag(state, 'bookArchitect');
  const llm = llmFor(state, architectAgent);
  if(!llm.apiKey) throw new Error('Не задан API-ключ.');
  const nodes = state.structure||[];
  const scenes = nodes.filter(n=>n.type==='scene');
  const pi = scenes.findIndex(n=>n.id===pivotScene.id);
  const downstream = scenes.slice(pi+1);
  if(!downstream.length) return [];

  const chTitle = id => (nodes.find(n=>n.type==='chapter'&&n.id===id)||{}).title || '';
  const p = state.project;
  const norm = p.sceneWords>0 ? Math.max(300, Math.min(4000, p.sceneWords))
    : Math.max(700, Math.min(2000, Math.round((p.targetWords||80000) / Math.max(1, scenes.length))));
  const wMin = Math.round(norm*0.80), wMax = Math.round(norm*1.20);
  const worldBlock = bibleForPrompt((state.bible||[]).filter(b=>b.source==='world' || b.pinned), p.synopsis||p.idea||'', 15);
  const sys = 'Ты — книжный архитектор. Изменилась одна сцена и повернула сюжет. Перепроектируй ВСЕ последующие сцены так, чтобы они логически следовали из изменения и не противоречили ему. Сохрани число сцен и их принадлежность главам. Не пишешь прозу.';
  const list = downstream.map((s,i)=>`${i+1}. [${chTitle(s.chapterId)}] «${s.title}» — ${s.brief}${s.entryState?` [на входе: ${s.entryState}]`:''}`).join('\n');
  const user = [
    `Жанр: ${p.genre||'роман'}. Синопсис: ${p.synopsis||p.idea||''}`,
    worldBlock ? `МИР КНИГИ (уже зафиксированные факты — не противоречь им):\n${worldBlock}` : '',
    '',
    `ИЗМЕНЁННАЯ СЦЕНА (поворот): «${pivotScene.title}» — ${pivotScene.brief}` + (pivotScene.emotion?` (эмоция: ${pivotScene.emotion})`:''),
    hint?`Направление автора: ${hint}`:'',
    '',
    `ПОСЛЕДУЮЩИЕ СЦЕНЫ (${downstream.length}) — перепиши каждую под новый поворот, по порядку:`,
    list,
    '',
    `targetWords каждой сцены — диапазон ${wMin}–${wMax} слов (±20% от базового объёма ${norm}), не выходи за пределы.`,
    'entryState у каждой сцены — заполняй ТОЛЬКО если на входе появилось что-то новое, не установленное в предыдущей сцене этой же цепочки; иначе пустая строка.',
    KNOWLEDGE_CONTINUITY_NOTE,
    BRIEF_DETAIL_NOTE,
    BRIEF_CHOICE_NOTE,
    PACING_NOTES[p.pacing] || PACING_NOTES.balanced,
    `Верни JSON: { "scenes": [ ${downstream.length} объектов по порядку: {"title":"…","brief":"3-4 предложения, см. БРИФ СЦЕНЫ выше","emotion":"…","entryState":"…","targetWords":число,"sceneType":"scene|sequel"} ] }. sceneType: "scene" — растущее напряжение, "sequel" — передышка (реакция→дилемма→решение). Ровно ${downstream.length} сцен. Только JSON.`,
  ].filter(Boolean).join('\n');

  // Живой инцидент (найдено при разборе МИРОК222, 52 сцены): maxTokens здесь
  // был жёстко зашит в 3600 независимо от downstream.length — тот же класс
  // бага, что уже чинили в runBookArchitect (см. её комментарий про «9900
  // токенов на 60 сцен не хватило»): пивот рано в книге даёт downstream в
  // 40+ сцен, каждая требует бриф 3-4 предложения (BRIEF_DETAIL_NOTE) +
  // entryState — 3600 токенов на такой объём гарантированно обрежет JSON.
  // Формула — та же пропорция (300 ток/сцена + запас), что и improve-режим
  // runBookArchitect, +20% по общему проходу этой сессии.
  // Потолок поднят 28000→36000, и тот же множитель настроек, что у
  // runBookArchitect/runBookArchitectPatch — одна ручка на все три функции.
  const maxTokens = Math.round(Math.max(3600, Math.min(36000, downstream.length*300 + 1200)) * 1.2 * (g.architectTokenMultiplier || 1));
  let lastErr='';
  startRun(null, 'Архитектор (каскадная перегенерация)');
  for(let attempt=0; attempt<=(g.retries??2); attempt++){
    const res = await callLLM({ ...llm, temperature:architectAgent.temp??0.7, messages:[{role:'system',content:sys},{role:'user',content:user}], maxTokens });
    assertNotTruncated(res, 'Книжный архитектор');
    const j = extractJSON(res.text);
    const arr = j && Array.isArray(j.scenes) ? j.scenes.filter(x=>x&&typeof x.brief==='string') : null;
    logStep({ agent:'bookArchitectDownstream', iter:attempt+1, input:`(каскад ${downstream.length} сцен, лимит ${maxTokens})`, output:res.text,
      tokensIn:res.tokensIn, tokensOut:res.tokensOut, cost:res.cost, verdict:{ ok:!!(arr&&arr.length), error:(arr&&arr.length)?undefined:'невалидный JSON' } });
    if(arr && arr.length){
      endRun('done');
      // применяем позиционно; число сцен не меняем (берём min для устойчивости)
      const applied = [];
      for(let i=0;i<Math.min(arr.length, downstream.length);i++){
        const sc = downstream[i], fr = arr[i];
        pushSceneVersion(sc);
        // Тот же фикс, что и в regenerateChapter(): без сброса status/text уже
        // написанная сцена оставалась «готово» со старым текстом, не подходящим
        // под новый бриф после каскадной перегенерации — молча уходило в экспорт.
        if(sc.status==='done' && sc.text){
          sc.proseVersions = sc.proseVersions || [];
          sc.proseVersions.unshift(sc.text);
          if(sc.proseVersions.length>10) sc.proseVersions.length=10;
          sc.status = 'todo';
        }
        sc.title=(fr.title||sc.title).trim();
        sc.brief=fr.brief.trim();
        sc.emotion=(fr.emotion||sc.emotion||'').trim();
        sc.entryState=(typeof fr.entryState==='string'?fr.entryState:sc.entryState||'').trim();
        if(Number(fr.targetWords)>0) sc.targetWords=clampSceneTargetWords(state, fr.targetWords);
        sc.sceneType = fr.sceneType==='sequel' ? 'sequel' : 'scene';
        applied.push(sc.id);
      }
      // Модель может вернуть МЕНЬШЕ сцен, чем реально в хвосте (arr.length <
      // downstream.length) — сис-промпт просит переписать ВСЕ последующие
      // сцены под новый поворот, но не гарантирует их число. Раньше «лишние»
      // сцены хвоста молча оставались НЕТРОНУТЫМИ — со старым брифом и (если
      // уже написаны) старой прозой, прямо противоречащей новому повороту, и
      // ничто не сигнализировало об этом автору (статус в UI показывал только
      // «Переписано сцен: N», без «из скольки»). Помечаем недостигнутый хвост
      // тем же флагом stale, что уже используется для «сцена выше изменилась».
      for(let i=arr.length; i<downstream.length; i++) if(downstream[i].status==='done') downstream[i].stale = true;
      return applied;
    }
    lastErr='невалидный JSON';
  }
  endRun('error');
  throw new Error('Каскадная перегенерация не удалась: '+lastErr);
}

// История версий сцены-скелета: сохранить текущие поля перед заменой / откатить.
const SCENE_FIELDS = ['title','brief','emotion','entryState','targetWords','sceneType'];
export function pushSceneVersion(scene){
  scene.briefVersions = scene.briefVersions || [];
  scene.briefVersions.unshift(Object.fromEntries(SCENE_FIELDS.map(f=>[f, scene[f]])));
  if(scene.briefVersions.length>10) scene.briefVersions.length=10;
}
export function revertScene(state, scene){
  if(!scene.briefVersions || !scene.briefVersions.length) return false;
  const v = scene.briefVersions.shift();
  SCENE_FIELDS.forEach(f=>{ if(v[f]!==undefined) scene[f]=v[f]; });
  // Версия в истории могла быть снята ДО того, как клэмп начал применяться
  // везде (или вообще предшествовать самому появлению этого поля в старой
  // книге) — откат не должен молча возвращать устаревшее вневилочное значение.
  if(scene.targetWords!=null) scene.targetWords = clampSceneTargetWords(state, scene.targetWords);
  return true;
}

// Применить скелет к плоскому state.structure[] (chapter|scene узлы).
// Перед заменой сохраняет прошлую структуру в историю (откат полного скелета).
export function applySkeleton(state, skeleton, uid){
  pushSkeletonVersion(state);
  // Имена персонажей ПРЕЖНЕЙ версии книги — нужны для предупреждения ниже.
  const oldCharNames = (state.characters||[]).map(c=>c.name).filter(Boolean);
  const nodes = [];
  for(const ch of skeleton.chapters){
    const chId = uid('ch');
    nodes.push({ id:chId, type:'chapter', title:ch.title, arc:ch.arc });
    for(const sc of ch.scenes){
      nodes.push({ id:uid('sc'), type:'scene', chapterId:chId, title:sc.title, brief:sc.brief,
        emotion:sc.emotion, entryState:sc.entryState||'', targetWords:sc.targetWords, sceneType:sc.sceneType||'scene', text:'', words:0, status:'todo' });
    }
  }
  state.structure = nodes;

  // ── Уборка после полной замены скелета ──
  // Живой инцидент (тестовый прогон): скелет перегенерировали дважды, и каждый
  // раз applySkeleton менял ТОЛЬКО state.structure. Канон, персонажи и сводки
  // сцен оставались от прежней версии книги: канон говорил «Очки ДР Глеба…»,
  // в персонажах числился Глеб, а новый бриф называл героя Даней. Прозаик
  // получил и то и другое, пошёл за каноном, Оценщик пожаловался на повтор
  // имени — и проза убрала имя вообще. Итог: герой без имени, сцена открывается
  // безличным «Нажал пальцем на дужку очков». Перегенерация скелета — штатное
  // действие (есть целый флоу «Улучшить»), так что это било по любой книге.
  //
  // Сводки сцен ключуются по id, а applySkeleton выдаёт всем сценам НОВЫЕ id —
  // значит прежние записи привязаны к сценам, которых больше не существует.
  // Это чистый мусор: он никогда не будет прочитан по назначению, но исправно
  // раздувает промпты через «ранее в книге». Удаляем — терять нечего.
  const liveIds = new Set(nodes.filter(n=>n.type==='scene').map(n=>n.id));
  const mem = state.memory || (state.memory = {});
  if(mem.scenes){
    Object.keys(mem.scenes).forEach(id=>{ if(!liveIds.has(id)) delete mem.scenes[id]; });
  }
  // Сводки глав — тем же правилом (id глав тоже новые).
  const liveChIds = new Set(nodes.filter(n=>n.type==='chapter').map(n=>n.id));
  if(mem.chapters){
    Object.keys(mem.chapters).forEach(id=>{ if(!liveChIds.has(id)) delete mem.chapters[id]; });
  }
  // Бегущий синопсис книги описывает выброшенную прозу — иначе он попадёт в
  // «РАНЕЕ В КНИГЕ (СИНОПСИС)» и будет противоречить новому скелету.
  if(mem.books && mem.books.__running__) mem.books.__running__ = { current: '' };

  // Иллюстрации сцен привязаны к sceneId — а он у всех сцен теперь новый, то
  // есть каждая картинка осиротела: она оплачена, видна в галерее, но ни в один
  // экспорт и ни под одну сцену больше не попадёт, и никто автору об этом не
  // скажет. Найдено живым прогоном уже ПОСЛЕ того, как здесь появилась уборка
  // памяти: чистка сводок эту половину проблемы не закрывала.
  // Перепривязываем по НАЗВАНИЮ сцены — при перегенерации скелета названия
  // обычно сохраняются (в том живом случае «Сбой перевода» совпало дословно), а
  // название куда устойчивее, чем сгенерированный id. Что не совпало — считаем
  // осиротевшим и показываем автору, но НЕ удаляем: это оплаченные картинки,
  // их можно перепривязать руками или использовать в другой сцене.
  const ic = state.illustrations || (state.illustrations = {});
  const byTitle = new Map();
  nodes.filter(n=>n.type==='scene').forEach(n=>{ if(!byTitle.has(n.title)) byTitle.set(n.title, n.id); });
  let relinked = 0, orphaned = 0;
  (ic.items||[]).forEach(it=>{
    if(it.type!=='scene') return;
    if(liveIds.has(it.sceneId)) return;              // уже указывает на живую сцену
    const found = it.sceneTitle && byTitle.get(it.sceneTitle);
    if(found){ it.sceneId = found; relinked++; }
    else { it.orphaned = true; orphaned++; }
  });
  state.illustrationsRelinked = (relinked || orphaned) ? { relinked, orphaned, at: Date.now() } : null;

  // А вот канон и персонажей НЕ удаляем сами: автор мог вносить их руками, и
  // молча снести его работу хуже, чем оставить лишнее. Вместо этого — флаг для
  // предупреждения в UI со списком имён, которых новый скелет может не знать.
  // Решение по нему принимает автор (см. renderStructure).
  const ghosts = findGhostCharacters(state, oldCharNames);
  // Пустой список пишем как { names: [] }, а не null: null теперь означает
  // «проверка ни разу не проводилась» и включает ленивый пересчёт в UI для
  // проектов, чей скелет пересобирали до появления этой проверки.
  state.canonStaleAfterSkeleton = { names: ghosts.slice(0,12), at: Date.now() };
}

// Имена в каноне, которых новый скелет не знает. Сравнение чисто позиционное:
// текущие персонажи против текущих брифов — снимок «прежней» книги не нужен,
// потому что applySkeleton не трогает state.characters. Поэтому ту же функцию
// можно вызвать задним числом для книги, собранной старой версией приложения.
export function findGhostCharacters(state, charNames){
  const nodes = state.structure || [];
  const briefs = nodes.filter(n=>n.type==='scene')
    .map(n=>`${n.title} ${n.brief||''} ${n.entryState||''}`).join(' ');
  if(!briefs.trim()) return [];   // скелета нет — сравнивать не с чем
  const names = charNames || (state.characters||[]).map(c=>c.name).filter(Boolean);
  return names.filter(name => name.length>=3 && !briefs.includes(name));
}

// Слияние ТОЧЕЧНОЙ правки (structurePatchMode) обратно в state.structure —
// в отличие от applySkeleton() (полная пересборка ВСЕХ глав), здесь заменяются
// только главы из patchChapters (см. runBookArchitectPatch/validateSkeletonPatch).
// Остальные главы и их сцены — ТЕ ЖЕ объекты с теми же id, тем же текстом и
// status: они вообще не участвовали в запросе к LLM, поэтому не могут быть
// случайно переписаны дрейфом формулировок (см. комментарий у applySkeleton
// про "точечно исправь" — инструкция не гарантия, полная регенерация всё
// равно слегка меняет нетронутые места). Побочный плюс: уже написанные сцены
// в незатронутых главах не стираются каждым «Улучшить», как раньше.
export function applySkeletonPatch(state, patchChapters, uid){
  pushSkeletonVersion(state);
  const chapterNodes = (state.structure||[]).filter(n=>n.type==='chapter');
  const byNumber = new Map(patchChapters.map(pc=>[pc.number, pc]));
  const nodes = [];
  chapterNodes.forEach((chNode, idx)=>{
    const patch = byNumber.get(idx+1);
    if(!patch){
      nodes.push(chNode);
      (state.structure||[]).filter(s=>s.type==='scene' && s.chapterId===chNode.id).forEach(sc=>nodes.push(sc));
      return;
    }
    const chId = uid('ch');
    nodes.push({ id:chId, type:'chapter', title:patch.title, arc:patch.arc });
    // ЭТА глава реально патчится — «Точечная правка» существует именно чтобы
    // не трогать сцены в НЕПАТЧЕННЫХ главах (см. комментарий выше), но раньше
    // сцены ВНУТРИ патченной главы всё равно создавались с нуля (новый id,
    // text:'') — уже написанная проза молча пропадала без резервной копии,
    // хотя regenerateChapter()/regenerateDownstream() (тот же по сути шаг —
    // переписать план сцен главы) специально уносят старый текст в
    // proseVersions перед сбросом. Переиспользуем старые узлы сцен
    // ПОЗИЦИОННО там, где патч сохранил ту же по номеру сцену — план
    // (бриф/эмоция/entryState/targetWords/sceneType) обновляется, текст (если
    // был) уходит в proseVersions, а не исчезает. Новые узлы создаются только
    // для сцен СВЕРХ прежнего числа (патч добавил сцену).
    const oldScenes = (state.structure||[]).filter(s=>s.type==='scene' && s.chapterId===chNode.id);
    patch.scenes.forEach((sc, i)=>{
      const targetWords = clampSceneTargetWords(state, sc.targetWords);
      const old = oldScenes[i];
      if(old){
        if(old.status==='done' && old.text){
          old.proseVersions = old.proseVersions || [];
          old.proseVersions.unshift(old.text);
          if(old.proseVersions.length>10) old.proseVersions.length=10;
          old.status = 'todo';
        }
        old.chapterId = chId;
        old.title = sc.title; old.brief = sc.brief; old.emotion = sc.emotion;
        old.entryState = sc.entryState||''; old.targetWords = targetWords; old.sceneType = sc.sceneType||'scene';
        nodes.push(old);
      } else {
        nodes.push({ id:uid('sc'), type:'scene', chapterId:chId, title:sc.title, brief:sc.brief,
          emotion:sc.emotion, entryState:sc.entryState||'', targetWords, sceneType:sc.sceneType||'scene', text:'', words:0, status:'todo' });
      }
    });
    // Если патч СОКРАТИЛ число сцен в этой главе — «лишние» старые сцены
    // (позиции ≥ patch.scenes.length) отсюда выпадают вместе с их прозой:
    // структурного места под них в новом плане просто нет. Это неизбежная
    // потеря при реальном сокращении числа сцен, не забытая защита — общий
    // откат всей структуры (pushSkeletonVersion выше, кнопка «↶ скелет»)
    // остаётся способом вернуть их, если сокращение окажется нежелательным.
  });
  state.structure = nodes;
}

// ── История полного скелета (откат неудачной перегенерации) ──
// Каждая версия хранит вместе со срезом structure[] и оценку Оценщика, которая
// была актуальна для НЕЁ (state.structureEval на момент вызова — это оценка
// именно той структуры, что сейчас архивируется, а не новой: applySkeleton
// зовёт push ДО перезаписи state.structure и ДО сброса state.structureEval).
// Раньше версия хранила только structure[], поэтому откат не мог восстановить
// оценку — приходилось молча сбрасывать её в null (см. revertSkeleton ниже).
export function pushSkeletonVersion(state){
  if(!state.structure || !state.structure.length) return; // нечего сохранять на первой генерации
  state.skeletonVersions = state.skeletonVersions || [];
  state.skeletonVersions.unshift({
    structure: JSON.parse(JSON.stringify(state.structure)),
    eval: state.structureEval ? JSON.parse(JSON.stringify(state.structureEval)) : null,
  });
  if(state.skeletonVersions.length>5) state.skeletonVersions.length=5;
}
export function revertSkeleton(state){
  if(!state.skeletonVersions || !state.skeletonVersions.length) return false;
  // Честный откат по истории (LIFO), не свап с одной и той же версией: раньше
  // повторный клик клал текущую структуру обратно на то же место в истории —
  // второй клик просто возвращал вперёд, а версии старше первой были
  // навсегда недостижимы, хотя счётчик кнопки обещал «N» шагов назад.
  const v = state.skeletonVersions.shift();
  state.structure = v.structure;
  state.structureEval = v.eval;
  return true;
}

